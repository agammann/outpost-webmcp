function makeFinding(seed: Seed, index: number): Finding {
  const [
    id,
    title,
    component,
    severity,
    exploitability,
    impact,
    confidence,
    status,
    effortDays,
    tags,
    reasoning,
    remediation,
  ] = seed;
  return {
    id,
    title,
    component,
    severity,
    exploitability,
    impact,
    confidence,
    status,
    effortDays,
    tags,
    reasoning,
    remediation,
    description: `${title} was identified during a fictional defensive review of ${component}. The finding contains no private target data or exploit payloads.`,
    evidence: [
      `Review trace ${id}-A confirms the affected control path.`,
      `Regression note ${id}-B documents the expected secure behavior.`,
      ...(severity === 'critical' || severity === 'high'
        ? [`Architecture note ${id}-C describes the impacted trust boundary.`]
        : []),
    ],
    relatedFindingIds:
      id === 'F-101'
        ? ['F-115']
        : id === 'F-103'
          ? ['F-112']
          : id === 'F-109'
            ? ['F-111']
            : [],
    notes: [],
    humanLocked: id === 'F-104',
    lockReason:
      id === 'F-104'
        ? 'Physical interaction is required; preserve analyst judgment during automatic reprioritization.'
        : undefined,
    priorityRank: index + 1,
  };
}

